// 13. REPORTS AND EVIDENCE MANAGEMENT VIEW
// ============================================================================
export const ReportsEvidenceView: React.FC<{
  data: OverviewPayload;
  onRefresh: () => Promise<void>;
}> = ({ data, onRefresh }) => {
  const [reportType, setReportType] = useState<string>('EXECUTIVE_SUMMARY');
  const [reportTitle, setReportTitle] = useState('');
  const [selectedReportId, setSelectedReportId] = useState<string>(data.reports[0]?.id || '');
  const [generating, setGenerating] = useState(false);

  const selectedReport: SecurityReport | undefined =
    data.reports.find((r) => r.id === selectedReportId) ?? data.reports[0];

  const handleGenerate = async (e: React.FormEvent) => {
    e.preventDefault();
    setGenerating(true);
    try {
      const created = await apiClient.generateReport({
        projectId: data.currentProject.id,
        reportType,
        title:
          reportTitle.trim() ||
          `${reportType.replace(/_/g, ' ')} — ${data.currentProject.code}`,
      });
      setReportTitle('');
      setSelectedReportId(created.id);
      await onRefresh();
    } finally {
      setGenerating(false);
    }
  };

  const handleDownloadMarkdown = (rep: SecurityReport) => {
    const md = [
      `# ${rep.title}`,
      `**Report ID:** ${rep.id} | **Type:** ${rep.reportType} | **Generated At:** ${rep.generatedAt}`,
      `**Generated By:** ${rep.generatedBy} | **Includes Synthetic Demo Data:** ${rep.includesSyntheticData ? 'YES [SYNTHETIC_DEMO]' : 'NO'}`,
      `\n## Scope & Methodology`,
      rep.scopeSummary,
      rep.methodology,
      `\n## Executive Summary`,
      rep.executiveSummary,
      ...rep.sections.map((s) => `\n## ${s.heading}\n${s.content}`),
      `\n## Limitations & Attestations`,
      ...rep.limitations.map((l) => `- ${l}`),
    ].join('\n\n');

    const blob = new Blob([md], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${rep.id}-${rep.reportType.toLowerCase()}.md`;
    a.click();
  };

  return (
    <div className="space-y-6">
      <SectionHeader
        title="Security Reports & Cryptographic Evidence Vault"
        subtitle="Generates evidence-backed reports from persisted project records. Explicitly separates confirmed findings from unverified hypotheses and flags synthetic data."
      />

      <form
        onSubmit={handleGenerate}
        className="p-5 bg-[#0F1523] border border-slate-800/80 rounded-lg grid grid-cols-1 md:grid-cols-4 gap-3 items-end"
      >
        <div>
          <label htmlFor="rep-type-select" className="block text-xs text-slate-400 mb-1">
            Report Template Type
          </label>
          <select
            id="rep-type-select"
            value={reportType}
            onChange={(e) => setReportType(e.target.value)}
            className="w-full px-3 py-2 text-xs bg-[#090D16] border border-slate-700 rounded text-slate-100"
          >
            <option value="EXECUTIVE_SUMMARY">EXECUTIVE_SUMMARY</option>
            <option value="TECHNICAL_ASSESSMENT">TECHNICAL_ASSESSMENT</option>
            <option value="VULNERABILITY_REGISTER">VULNERABILITY_REGISTER</option>
            <option value="ASSET_INVENTORY">ASSET_INVENTORY</option>
            <option value="REMEDIATION_PLAN">REMEDIATION_PLAN</option>
            <option value="INCIDENT_REPORT">INCIDENT_REPORT</option>
            <option value="ATTACK_PATH_ANALYSIS">ATTACK_PATH_ANALYSIS</option>
            <option value="LAB_EXERCISE_REPORT">LAB_EXERCISE_REPORT</option>
            <option value="AUDIT_COMPLIANCE">AUDIT_COMPLIANCE</option>
          </select>
        </div>
        <div className="md:col-span-2">
          <label htmlFor="rep-title-input" className="block text-xs text-slate-400 mb-1">
            Custom Report Title
          </label>
          <input
            id="rep-title-input"
            type="text"
            value={reportTitle}
            onChange={(e) => setReportTitle(e.target.value)}
            placeholder="e.g. Q4 Board Security Assurance Summary"
            className="w-full px-3 py-2 text-xs bg-[#090D16] border border-slate-700 rounded text-slate-100"
          />
        </div>
        <button
          type="submit"
          disabled={generating}
          className="px-4 py-2 text-xs font-medium text-slate-950 bg-cyan-400 hover:bg-cyan-300 rounded-md"
        >
          {generating ? 'Compiling Report...' : 'Generate Evidence Report'}
        </button>
      </form>

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        <div className="lg:col-span-4 space-y-2">
          <h2 className="text-sm font-semibold text-slate-100">
            Generated Reports ({data.reports.length})
          </h2>
          {data.reports.map((rep) => (
            <button
              key={rep.id}
              type="button"
              onClick={() => setSelectedReportId(rep.id)}
              className={`w-full text-left p-3.5 rounded-lg border transition-colors ${
                selectedReport?.id === rep.id
                  ? 'bg-cyan-950/30 border-cyan-500/50 text-slate-100'
                  : 'bg-[#0F1523] border-slate-800 text-slate-300 hover:border-slate-700'
              }`}
            >
              <div className="text-xs font-mono text-cyan-300">{rep.reportType}</div>
              <div className="text-sm font-semibold mt-0.5">{rep.title}</div>
              <div className="text-[11px] font-mono text-slate-400 mt-1">
                Verified: {rep.verifiedFindingsCount} · Candidates: {rep.unverifiedHypothesesCount}
              </div>
            </button>
          ))}
        </div>

        <div className="lg:col-span-8 bg-[#0F1523] border border-slate-800/80 rounded-lg p-5 space-y-4">
          {selectedReport ? (
            <>
              <div className="flex flex-wrap items-center justify-between gap-2 pb-3 border-b border-slate-800">
                <div>
                  <div className="text-xs font-mono text-slate-400">
                    {selectedReport.id} · Generated {selectedReport.generatedAt.slice(0, 19)} UTC by{' '}
                    {selectedReport.generatedBy}
                  </div>
                  <h3 className="text-lg font-semibold text-slate-100 mt-0.5">
                    {selectedReport.title}
                  </h3>
                </div>
                <button
                  type="button"
                  onClick={() => handleDownloadMarkdown(selectedReport)}
                  className="px-3 py-1.5 text-xs font-medium text-slate-950 bg-cyan-400 hover:bg-cyan-300 rounded-md"
                >
                  Download Report (.MD)
                </button>
              </div>

              <div className="text-xs text-slate-300 space-y-3">
                <div>
                  <span className="font-semibold text-slate-100">Scope Attestation:</span>{' '}
                  {selectedReport.scopeSummary}
                </div>
                <div>
                  <span className="font-semibold text-slate-100">Executive Summary:</span>{' '}
                  {selectedReport.executiveSummary}
                </div>
                {selectedReport.sections.map((sec, i) => (
                  <div key={i} className="p-3 bg-[#090D16] border border-slate-800 rounded space-y-1">
                    <div className="font-semibold text-cyan-300">{sec.heading}</div>
                    <div className="whitespace-pre-line text-slate-300 font-mono text-[11px]">
                      {sec.content}
                    </div>
                  </div>
                ))}
              </div>
            </>
          ) : (
            <div className="text-xs text-slate-400">Select or generate a report to preview.</div>
          )}
        </div>
      </div>

      {/* Cryptographic Evidence Vault */}
      <div className="space-y-3">
        <h2 className="text-sm font-semibold text-slate-100">
          SHA-256 Chain-of-Custody Evidence Artifacts ({data.evidence.length})
        </h2>
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {data.evidence.map((ev) => (
            <div
              key={ev.id}
              className="p-4 bg-[#0F1523] border border-slate-800/80 rounded-lg space-y-2 text-xs"
            >
              <div className="flex items-center justify-between font-mono">
                <span className="text-cyan-300 font-semibold">{ev.id}</span>
                <span className="text-slate-400">
                  {ev.artifactType} · Linked: {ev.linkedEntityId}
                </span>
              </div>
              <div className="font-semibold text-slate-100">{ev.title}</div>
              <div className="font-mono text-[11px] text-emerald-400 truncate">
                SHA-256: {ev.sha256Digest}
              </div>
              <pre className="p-2.5 bg-[#090D16] border border-slate-800 rounded font-mono text-[11px] text-slate-300 overflow-x-auto">
                {ev.rawPayloadRedacted}
              </pre>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
};

